import { readFile } from "node:fs/promises";
import { describe, expect, it } from "vitest";
import { compileConfig } from "./compiler.js";
import type {
  CalqueConfigDefinition,
  CollectionDefinition,
  ColumnDefinition,
} from "./domain.js";
import { generateBindings } from "./generate.js";
import { POSTGRES_TYPES } from "./postgres-types.js";

const load = async (): Promise<CalqueConfigDefinition> =>
  JSON.parse(
    await readFile(
      new URL(
        "../../../../tests/fixtures/config/incident-ops.config.json",
        import.meta.url,
      ),
      "utf8",
    ),
  ) as CalqueConfigDefinition;

/** The fixture with its one collection replaced by `work_items` of `columns`. */
async function workItems(
  columns: readonly ColumnDefinition[],
  operations: readonly string[],
): Promise<CalqueConfigDefinition> {
  const definition = await load();
  const [issues] = definition.collections;
  if (!issues) throw new Error("fixture collection is missing");
  const collection: CollectionDefinition = {
    ...issues,
    id: "work_items",
    relation: { schema: "public", table: "work_items" },
    columns,
    primaryKey: ["id"],
  };
  return {
    ...definition,
    collections: [collection],
    commands: [
      {
        id: "edit-work-items",
        kind: "crud",
        collection: "work_items",
        operations:
          operations as CalqueConfigDefinition["commands"][number]["operations"],
        writableColumns: columns
          .map(({ name }) => name)
          .filter((name) => name !== "id"),
      },
    ],
  };
}

describe("generateBindings", () => {
  it("keys a partitioned collection by its tenant column and a shared one by its own key", async () => {
    const definition = JSON.parse(
      await readFile(
        new URL(
          "../../../../tests/fixtures/config/serve-tenants.config.json",
          import.meta.url,
        ),
        "utf8",
      ),
    ) as CalqueConfigDefinition;
    const { bindings } = generateBindings(compileConfig(definition));
    expect(bindings).toContain(
      'export type TasksKey = Pick<TasksRow, "tenant_id" | "id">;',
    );
    expect(bindings).toContain(
      'export type PrioritiesKey = Pick<PrioritiesRow, "id">;',
    );
  });

  it("renders the fixture's bindings and start module exactly", async () => {
    const generated = generateBindings(compileConfig(await load()));

    expect(generated.bindings).toBe(
      [
        "// Generated by calque-bindings. Do not edit.",
        'import type { CollectionShape } from "@calque/client";',
        'import { createGeneratedClientSchema } from "@calque/client/generated";',
        "",
        "export interface IssuesRow {",
        "  readonly id: string;",
        "  readonly organization_id: string;",
        "  readonly status: string;",
        "  readonly title: string;",
        "}",
        'export type IssuesKey = Pick<IssuesRow, "id">;',
        'export type IssuesPatch = Partial<Pick<IssuesRow, "status" | "title">>;',
        "",
        "export type CalqueCollections = {",
        "  readonly issues: CollectionShape<IssuesRow, IssuesKey, never, IssuesPatch, true>;",
        "};",
        "",
        'declare module "@calque/client" {',
        "  interface Register {",
        "    collections: CalqueCollections;",
        "  }",
        "}",
        "",
        "export const schema = createGeneratedClientSchema<CalqueCollections>({",
        "  collections: [",
        "    {",
        '      id: "issues",',
        '      tableId: "public.issues",',
        "      columns: [",
        '        { name: "id", kind: "uuid" },',
        '        { name: "organization_id", kind: "uuid" },',
        '        { name: "status", kind: "text" },',
        '        { name: "title", kind: "text" },',
        "      ],",
        '      primaryKey: ["id"],',
        "      writes: {",
        '        operations: ["delete", "update"],',
        '        writableColumns: ["status", "title"],',
        "      },",
        "    },",
        "  ],",
        "});",
        "",
      ].join("\n"),
    );
    expect(generated.start).toBe(
      [
        "// Generated by calque-bindings. Do not edit.",
        "",
        "/** The tables the page's bootstrap request asks for, as `schema.table`. */",
        "export const requiredTables: readonly string[] = [",
        '  "public.issues",',
        "];",
        "",
      ].join("\n"),
    );
  });

  it("depends only on what the configuration declares, not its order", async () => {
    const definition = await load();
    const reordered = structuredClone(definition) as {
      collections: { columns: ColumnDefinition[] }[];
    } & CalqueConfigDefinition;
    for (const collection of reordered.collections)
      collection.columns.reverse();

    expect(generateBindings(compileConfig(reordered))).toEqual(
      generateBindings(compileConfig(definition)),
    );
  });

  it("types every enrolled PostgreSQL type, a nullable column, and an insert of the whole row", async () => {
    const columns: ColumnDefinition[] = [
      { name: "id", postgresType: "int8", nullable: false },
      ...[...POSTGRES_TYPES.keys()].map((postgresType) => ({
        name: `${postgresType}_value`,
        postgresType,
        nullable: false,
      })),
      { name: "Due Date", postgresType: "date", nullable: true },
    ];
    const bindings = generateBindings(
      compileConfig(await workItems(columns, ["insert", "update", "delete"])),
    ).bindings;

    expect(bindings).toContain(
      [
        "export interface WorkItemsRow {",
        '  readonly "Due Date": string | null;',
        "  readonly bool_value: boolean;",
        "  readonly bpchar_value: string;",
        "  readonly bytea_value: Uint8Array;",
        "  readonly date_value: string;",
        "  readonly float4_value: number;",
        "  readonly float8_value: number;",
        "  readonly id: bigint;",
        "  readonly int2_value: number;",
        "  readonly int4_value: number;",
        "  readonly int8_value: bigint;",
        "  readonly json_value: unknown;",
        "  readonly jsonb_value: unknown;",
        "  readonly numeric_value: string;",
        "  readonly text_value: string;",
        "  readonly time_value: string;",
        "  readonly timestamp_value: string;",
        "  readonly timestamptz_value: string;",
        "  readonly uuid_value: string;",
        "  readonly varchar_value: string;",
        "}",
        'export type WorkItemsKey = Pick<WorkItemsRow, "id">;',
        "export type WorkItemsInsert = WorkItemsRow;",
      ].join("\n"),
    );
    expect(bindings).toContain(
      '  readonly work_items: CollectionShape<WorkItemsRow, WorkItemsKey, WorkItemsInsert, WorkItemsPatch, true, "int2_value" | "int4_value">;',
    );
    expect(bindings).toContain('        { name: "Due Date", kind: "date" },');
    expect(bindings).toContain(
      '        { name: "int2_value", kind: "int32" },',
    );
    expect(bindings).toContain(
      '        { name: "int8_value", kind: "int64" },',
    );
    expect(bindings).toContain(
      '        operations: ["delete", "insert", "update"],',
    );
  });

  it("gives an operation no command allows no type", async () => {
    const columns: ColumnDefinition[] = [
      { name: "id", postgresType: "int8", nullable: false },
      { name: "title", postgresType: "text", nullable: false },
    ];
    const bindings = generateBindings(
      compileConfig(await workItems(columns, ["update"])),
    ).bindings;

    expect(bindings).not.toContain("WorkItemsInsert");
    expect(bindings).toContain(
      "  readonly work_items: CollectionShape<WorkItemsRow, WorkItemsKey, never, WorkItemsPatch>;",
    );
  });

  it("names the int2 and int4 columns after the delete flag", async () => {
    const columns: ColumnDefinition[] = [
      { name: "id", postgresType: "int8", nullable: false },
      { name: "rank", postgresType: "int4", nullable: true },
    ];
    const bindings = generateBindings(
      compileConfig(await workItems(columns, ["update"])),
    ).bindings;

    expect(bindings).toContain(
      '  readonly work_items: CollectionShape<WorkItemsRow, WorkItemsKey, never, WorkItemsPatch, false, "rank">;',
    );
  });

  it("refuses collection ids that spell the same type names", async () => {
    const definition = await load();
    const [original] = definition.collections;
    const [command] = definition.commands;
    if (!original || !command) throw new Error("fixture is incomplete");
    // A collection is named after its table, so the two ids are two tables,
    // `public."issue-items"` and `public.issue_items`.
    const collections = [
      {
        ...original,
        id: "issue-items",
        relation: { ...original.relation, table: "issue-items" },
      },
      {
        ...original,
        id: "issue_items",
        relation: { ...original.relation, table: "issue_items" },
      },
    ];
    const manifest = compileConfig({
      ...definition,
      collections,
      commands: [{ ...command, collection: "issue_items" }],
    });

    expect(() => generateBindings(manifest)).toThrowError(
      "$.collections: collection ids issue-items and issue_items generate the same TypeScript type names; rename one collection",
    );
  });
});
