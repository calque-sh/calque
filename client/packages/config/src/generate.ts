import { ConfigError } from "./compiler.js";
import type {
  CalqueManifest,
  CollectionDefinition,
  CrudCommandDefinition,
} from "./domain.js";
import { POSTGRES_TYPES, type GeneratedType } from "./postgres-types.js";

/** The text of the two modules `calque-bindings` writes. */
export interface GeneratedBindings {
  /** `calque.generated.ts`: the row types, `CalqueCollections` and `schema`. */
  readonly bindings: string;
  /** `calque.start.generated.ts`: `requiredTables`, importing nothing. */
  readonly start: string;
}

const HEADER = "// Generated by calque-bindings. Do not edit.";
const IDENTIFIER = /^[A-Za-z_$][\w$]*$/u;

interface Names {
  readonly row: string;
  readonly key: string;
  readonly insert: string;
  readonly patch: string;
}

function typeName(id: string): string {
  return id
    .split(/[._-]/u)
    .map((part) => `${part.charAt(0).toUpperCase()}${part.slice(1)}`)
    .join("");
}

function namesOf(collection: CollectionDefinition): Names {
  const base = typeName(collection.id);
  return {
    row: `${base}Row`,
    key: `${base}Key`,
    insert: `${base}Insert`,
    patch: `${base}Patch`,
  };
}

function quoted(value: string): string {
  return JSON.stringify(value);
}

/** `value` as a property name: bare when it is an identifier. */
function property(value: string): string {
  return IDENTIFIER.test(value) ? value : quoted(value);
}

function list(values: readonly string[]): string {
  return `[${values.map(quoted).join(", ")}]`;
}

function union(values: readonly string[]): string {
  return values.map(quoted).join(" | ");
}

function generatedType(name: string): GeneratedType {
  const type = POSTGRES_TYPES.get(name);
  // `compileConfig` admits only the types in the map.
  if (!type) throw new TypeError(`unmapped PostgreSQL type ${name}`);
  return type;
}

function crudFor(
  manifest: CalqueManifest,
  collection: CollectionDefinition,
): CrudCommandDefinition | undefined {
  return manifest.commands.find(
    (command) => command.collection === collection.id,
  );
}

/** Refuses two collections whose ids spell the same type names. */
function checkNames(collections: readonly CollectionDefinition[]): void {
  const owners = new Map<string, string>();
  for (const collection of collections) {
    const owner = owners.get(typeName(collection.id));
    if (owner !== undefined)
      throw new ConfigError(
        "$.collections",
        `collection ids ${owner} and ${collection.id} generate the same TypeScript type names; rename one collection`,
      );
    owners.set(typeName(collection.id), collection.id);
  }
}

function collectionTypes(
  collection: CollectionDefinition,
  crud: CrudCommandDefinition | undefined,
): string[] {
  const names = namesOf(collection);
  const lines = [`export interface ${names.row} {`];
  for (const column of collection.columns)
    lines.push(
      `  readonly ${property(column.name)}: ${generatedType(column.postgresType).typescript}${column.nullable ? " | null" : ""};`,
    );
  lines.push(
    "}",
    `export type ${names.key} = Pick<${names.row}, ${union(collection.primaryKey)}>;`,
  );
  if (crud?.operations.includes("insert"))
    lines.push(`export type ${names.insert} = ${names.row};`);
  if (crud?.operations.includes("update"))
    lines.push(
      `export type ${names.patch} = Partial<Pick<${names.row}, ${union(crud.writableColumns)}>>;`,
    );
  lines.push("");
  return lines;
}

function collectionShape(
  collection: CollectionDefinition,
  crud: CrudCommandDefinition | undefined,
): string {
  const names = namesOf(collection);
  const operations = crud?.operations ?? [];
  const int32 = collection.columns
    .filter(({ postgresType }) => generatedType(postgresType).kind === "int32")
    .map(({ name }) => name);
  const remove = operations.includes("delete");
  const parameters = [
    names.row,
    names.key,
    operations.includes("insert") ? names.insert : "never",
    operations.includes("update") ? names.patch : "never",
    ...(remove || int32.length > 0 ? [String(remove)] : []),
    ...(int32.length > 0 ? [union(int32)] : []),
  ];
  return `  readonly ${property(collection.id)}: CollectionShape<${parameters.join(", ")}>;`;
}

function collectionDescriptor(
  collection: CollectionDefinition,
  crud: CrudCommandDefinition | undefined,
): string[] {
  return [
    "    {",
    `      id: ${quoted(collection.id)},`,
    `      tableId: ${quoted(`${collection.relation.schema}.${collection.relation.table}`)},`,
    "      columns: [",
    ...collection.columns.map(
      (column) =>
        `        { name: ${quoted(column.name)}, kind: ${quoted(generatedType(column.postgresType).kind)} },`,
    ),
    "      ],",
    `      primaryKey: ${list(collection.primaryKey)},`,
    ...(crud
      ? [
          "      writes: {",
          `        operations: ${list(crud.operations)},`,
          `        writableColumns: ${list(crud.writableColumns)},`,
          "      },",
        ]
      : []),
    "    },",
  ];
}

/**
 * The bindings and the start module for a compiled configuration, as
 * `calque-bindings` writes them. Their text depends on nothing else, so a
 * checked-in render stays current until the configuration changes.
 */
export function generateBindings(manifest: CalqueManifest): GeneratedBindings {
  const { collections } = manifest;
  checkNames(collections);
  const bindings = [
    HEADER,
    'import type { CollectionShape } from "@calque/client";',
    'import { createGeneratedClientSchema } from "@calque/client/generated";',
    "",
    ...collections.flatMap((collection) =>
      collectionTypes(collection, crudFor(manifest, collection)),
    ),
    "export type CalqueCollections = {",
    ...collections.map((collection) =>
      collectionShape(collection, crudFor(manifest, collection)),
    ),
    "};",
    "",
    'declare module "@calque/client" {',
    "  interface Register {",
    "    collections: CalqueCollections;",
    "  }",
    "}",
    "",
    "export const schema = createGeneratedClientSchema<CalqueCollections>({",
    "  collections: [",
    ...collections.flatMap((collection) =>
      collectionDescriptor(collection, crudFor(manifest, collection)),
    ),
    "  ],",
    "});",
    "",
  ];
  const start = [
    HEADER,
    "",
    "/** The tables the page's bootstrap request asks for, as `schema.table`. */",
    "export const requiredTables: readonly string[] = [",
    ...collections
      .map(({ relation }) => `${relation.schema}.${relation.table}`)
      .sort()
      .map((relation) => `  ${quoted(relation)},`),
    "];",
    "",
  ];
  return Object.freeze({
    bindings: bindings.join("\n"),
    start: start.join("\n"),
  });
}
